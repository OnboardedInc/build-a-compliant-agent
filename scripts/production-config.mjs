// Writes wrangler.production.jsonc (git-ignored): wrangler.jsonc with the real D1 database id.
// The tracked wrangler.jsonc keeps a zero placeholder, because this repository is public.
// The id is looked up by the database's name in the account wrangler is logged in to, so it is
// never stored in a tracked file. `npm run deploy` and `npm run migrate:remote` run this first.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { withBaseConfig } from "./base-config.mjs";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const PLACEHOLDER = "00000000-0000-0000-0000-000000000000";
const source = readFileSync(resolve(REPO, "wrangler.jsonc"), "utf8");
const name = source.match(/"database_name"\s*:\s*"([^"]+)"/)?.[1];
if (!name) throw new Error("wrangler.jsonc names no D1 database.");
if (!source.includes(PLACEHOLDER)) throw new Error("wrangler.jsonc should keep the zero placeholder database id.");
const domain = process.env.BCA_SITE_DOMAIN;
const config = withBaseConfig(source, process.env.BCA_BASE_PATH);

const wrangler = resolve(REPO, "node_modules/.bin/wrangler");
const list = JSON.parse(execFileSync(wrangler, ["d1", "list", "--json"], { cwd: REPO, encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] }));
const db = list.find((d) => d.name === name);
if (!db) throw new Error(`No D1 database named ${name} in this account. Create it with \`npx wrangler d1 create ${name}\`.`);

let output = config.replace(PLACEHOLDER, db.uuid);
if (domain) output = output.replace("{\n", `{\n\t"routes": ${JSON.stringify([{ pattern: domain, custom_domain: true }])},\n`);
const header = "// Generated by scripts/production-config.mjs. Git-ignored: it holds the real D1 database id.\n";
writeFileSync(resolve(REPO, "wrangler.production.jsonc"), header + output);
console.log(`wrangler.production.jsonc written for D1 database ${name}.`);
