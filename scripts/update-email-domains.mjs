// Writes src/server/data/personalEmailDomains.ts: the domains a work email cannot be at.
// Two open lists, joined:
//   free-email-domains (personal mailbox providers, based on HubSpot's blocked list)
//     https://github.com/microlinkhq/free-email-domains   MIT License, Copyright (c) 2017 Microlink
//   disposable-email-domains (throwaway inboxes)
//     https://github.com/disposable-email-domains/disposable-email-domains   CC0 1.0
// Run `node scripts/update-email-domains.mjs` to refresh it, then read the diff before committing.
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const FREE = "https://raw.githubusercontent.com/microlinkhq/free-email-domains/master/domains.json";
const DISPOSABLE = "https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf";
const get = async (url) => { const response = await fetch(url); if (!response.ok) throw new Error(`${url} answered ${response.status}`); return response.text(); };
const [free, disposable] = await Promise.all([get(FREE), get(DISPOSABLE)]);
const domain = /^(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,}$/;
const clean = (list) => list.map((entry) => String(entry).trim().toLowerCase()).filter((entry) => entry.length <= 100 && domain.test(entry));
const freeList = clean(JSON.parse(free));
const disposableList = clean(disposable.split("\n").filter((line) => line && !line.startsWith("#")));
if (freeList.length < 20000 || disposableList.length < 5000) throw new Error(`The lists look wrong: ${freeList.length} free, ${disposableList.length} disposable.`);
const all = [...new Set([...freeList, ...disposableList])].sort();
const out = resolve(dirname(fileURLToPath(import.meta.url)), "../src/server/data/personalEmailDomains.ts");
writeFileSync(out, `// Generated by scripts/update-email-domains.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// ${all.length} domains: ${freeList.length} personal mailbox providers and ${disposableList.length} throwaway inboxes, joined.
// Sources: microlinkhq/free-email-domains (MIT License, Copyright (c) 2017 Microlink) and
// disposable-email-domains/disposable-email-domains (CC0 1.0).
/** One domain per line. */
export const PERSONAL_EMAIL_DOMAIN_LIST = \`${all.join("\n")}\`;
`);
console.log(`${all.length} domains written (${freeList.length} personal, ${disposableList.length} throwaway).`);
